export function getTeamDisplayName(englishName: string | null | undefined): string {
  if (!englishName) return 'Por definir';
  const trimmed = englishName.trim();
  if (!trimmed || trimmed === 'TBD') return 'Por definir';
  return (
    TEAM_DISPLAY_NAME_ES[trimmed]
    ?? Object.entries(TEAM_DISPLAY_NAME_ES).find(
      ([k]) => k.toLowerCase() === trimmed.toLowerCase()
    )?.[1]
    ?? trimmed
  );
}
